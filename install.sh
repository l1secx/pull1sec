#!/usr/bin/env bash
# Pull1sec installer: curl -fsSL https://raw.githubusercontent.com/l1secx/pull1sec/main/install.sh | bash
#
# Installs the app under ${PULL1SEC_HOME:-~/.local/share/pull1sec}, creates a
# private virtual environment for the Python dependencies, and puts a
# `pull1sec` launcher in ${PULL1SEC_BIN_DIR:-~/.local/bin}. Nothing is
# installed globally and no environment needs to be activated.
#
# Options:
#   --uninstall     remove the launcher and the installed environment
#   --help          show this help
#
# Environment:
#   PULL1SEC_REPO       repository URL   (default https://github.com/l1secx/pull1sec)
#   PULL1SEC_REF        branch or tag     (default main)
#   PULL1SEC_HOME       install root      (default ${XDG_DATA_HOME:-~/.local/share}/pull1sec)
#   PULL1SEC_BIN_DIR    launcher dir      (default ~/.local/bin)
#   PULL1SEC_PYTHON     interpreter to use (default: first python3/python >= 3.11)

set -euo pipefail

REPO="${PULL1SEC_REPO:-https://github.com/l1secx/pull1sec}"
REF="${PULL1SEC_REF:-main}"
DATA_DIR="${PULL1SEC_HOME:-${XDG_DATA_HOME:-$HOME/.local/share}/pull1sec}"
APP_DIR="$DATA_DIR/app"
VENV_DIR="$DATA_DIR/venv"
BIN_DIR="${PULL1SEC_BIN_DIR:-$HOME/.local/bin}"
STAMP="$DATA_DIR/venv.requirements"
MIN_MINOR=11

say() { printf '  %s\n' "$*"; }
note() { printf '  %s\n' "$*" >&2; }
err() { printf 'hata: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<'HELP'
Pull1sec installer

  curl -fsSL https://raw.githubusercontent.com/l1secx/pull1sec/main/install.sh | bash
  curl -fsSL .../install.sh | bash -s -- --uninstall

Options:
  --uninstall     remove the launcher and the installed environment
  --help          show this help

Environment:
  PULL1SEC_REPO       repository URL   (default https://github.com/l1secx/pull1sec)
  PULL1SEC_REF        branch or tag     (default main)
  PULL1SEC_HOME       install root      (default ${XDG_DATA_HOME:-~/.local/share}/pull1sec)
  PULL1SEC_BIN_DIR    launcher dir      (default ~/.local/bin)
  PULL1SEC_PYTHON     interpreter to use (default: first python3/python >= 3.11)
HELP
}

need_python() {
  local candidate
  if [ -n "${PULL1SEC_PYTHON:-}" ]; then
    candidate="$PULL1SEC_PYTHON"
    "$candidate" -c "import sys; sys.exit(0 if sys.version_info >= (3, $MIN_MINOR) else 1)" 2>/dev/null ||
      err "PULL1SEC_PYTHON=$candidate çalışmıyor ya da Python 3.$MIN_MINOR+ değil."
    printf '%s' "$candidate"
    return
  fi
  for candidate in python3 python; do
    if command -v "$candidate" >/dev/null 2>&1 &&
      "$candidate" -c "import sys; sys.exit(0 if sys.version_info >= (3, $MIN_MINOR) else 1)" 2>/dev/null; then
      printf '%s' "$candidate"
      return
    fi
  done
  err "Python 3.$MIN_MINOR+ bulunamadı. https://www.python.org/downloads/ adresinden kurun."
}

hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    openssl dgst -sha256 "$1" | awk '{print $NF}'
  fi
}

venv_python="$VENV_DIR/bin/python"

env_ready() {
  [ -x "$venv_python" ] &&
    "$venv_python" -c 'import fastapi, uvicorn, yt_dlp' >/dev/null 2>&1
}

install_requirements() {
  if command -v uv >/dev/null 2>&1; then
    uv pip install --python "$venv_python" --upgrade -r "$1"
    return
  fi
  if ! "$venv_python" -m pip --version >/dev/null 2>&1; then
    "$venv_python" -m ensurepip --upgrade
  fi
  "$venv_python" -m pip install --upgrade -r "$1"
}

ensure_env() {
  local wanted current python
  wanted="$(hash_file "$APP_DIR/requirements.txt")"
  current="$(cat "$STAMP" 2>/dev/null || true)"
  if [ "$wanted" = "$current" ] && env_ready; then
    return
  fi

  rm -f "$STAMP"
  python="$(need_python)"

  # A stale environment (moved Python, OS upgrade) is rebuilt instead of
  # failing with a confusing interpreter error.
  if [ -e "$venv_python" ] && ! "$venv_python" -c 'pass' >/dev/null 2>&1; then
    say "Eski Python ortamı bozuk, yeniden oluşturuluyor"
    rm -rf "$VENV_DIR"
  fi

  if [ ! -x "$venv_python" ]; then
    say "Python ortamı hazırlanıyor"
    if command -v uv >/dev/null 2>&1; then
      uv venv --python "$python" "$VENV_DIR"
    else
      "$python" -m venv "$VENV_DIR" ||
        err "Python ortamı oluşturulamadı. python3-venv paketini kurun ya da uv kullanın."
    fi
  fi
  [ -x "$venv_python" ] || err "Python ortamı oluşturulamadı: $VENV_DIR"

  say "Bağımlılıklar kuruluyor (bu ilk seferde birkaç dakika sürebilir)"
  install_requirements "$APP_DIR/requirements.txt"
  env_ready || err "Bağımlılıklar kuruldu ama içe aktarılamadı. Silip yeniden deneyin: rm -rf \"$VENV_DIR\""
  printf '%s\n' "$wanted" >"$STAMP"
}

write_launcher() {
  mkdir -p "$BIN_DIR"
  if [ -e "$BIN_DIR/pull1sec" ] && ! grep -q "Generated by pull1sec install.sh" "$BIN_DIR/pull1sec" 2>/dev/null; then
    err "$BIN_DIR/pull1sec zaten var ve bu kuruluma ait değil. Taşıyın ya da PULL1SEC_BIN_DIR belirtin."
  fi
  cat >"$BIN_DIR/pull1sec" <<LAUNCHER
#!/bin/sh
# Generated by pull1sec install.sh. Remove with: install.sh --uninstall
PYTHONPATH="$APP_DIR\${PYTHONPATH:+:\$PYTHONPATH}"
export PYTHONPATH
exec "$venv_python" -m pull1sec "\$@"
LAUNCHER
  chmod +x "$BIN_DIR/pull1sec"
  say "Komut: $BIN_DIR/pull1sec"
}

install_app() {
  local tmp src archive
  command -v curl >/dev/null 2>&1 || err "curl gerekli."
  command -v tar >/dev/null 2>&1 || err "tar gerekli."

  tmp="$(mktemp -d)"
  # shellcheck disable=SC2064
  trap "rm -rf '$tmp'" EXIT

  case "$REF" in
    v[0-9]*) archive="$REPO/archive/refs/tags/$REF.tar.gz" ;;
    *) archive="$REPO/archive/refs/heads/$REF.tar.gz" ;;
  esac

  say "İndiriliyor: $archive"
  curl -fsSL "$archive" -o "$tmp/src.tar.gz" ||
    err "indirilemedi. PULL1SEC_REPO ve PULL1SEC_REF değerlerini kontrol edin."
  tar -xzf "$tmp/src.tar.gz" -C "$tmp"
  src="$(find "$tmp" -mindepth 1 -maxdepth 1 -type d | head -n 1)"
  [ -n "$src" ] && [ -f "$src/requirements.txt" ] || err "arşiv beklenen yapıda değil."

  mkdir -p "$DATA_DIR"
  rm -rf "$APP_DIR.new"
  mkdir -p "$APP_DIR.new"
  cp -R "$src/." "$APP_DIR.new/"
  rm -rf "$APP_DIR"
  mv "$APP_DIR.new" "$APP_DIR"
  say "Uygulama: $APP_DIR"

  ensure_env
  write_launcher

  case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *)
      note "uyarı: $BIN_DIR PATH'te değil. Kabuğunuza şunu ekleyin:"
      note "  export PATH=\"$BIN_DIR:\$PATH\""
      ;;
  esac

  if ! command -v ffmpeg >/dev/null 2>&1; then
    note "uyarı: ffmpeg bulunamadı. Video birleştirme ve ses dönüştürme çalışmaz."
  fi

  printf '\n'
  say "Kurulum tamam. Sıradaki adımlar:"
  say "  pull1sec user set     # hesabı oluştur"
  say "  pull1sec              # sunucuyu başlat"
}

uninstall_app() {
  if [ -f "$BIN_DIR/pull1sec" ] && grep -q "Generated by pull1sec install.sh" "$BIN_DIR/pull1sec" 2>/dev/null; then
    rm -f "$BIN_DIR/pull1sec"
    say "Kaldırıldı: $BIN_DIR/pull1sec"
  else
    note "not: $BIN_DIR/pull1sec bu kuruluma ait değil, dokunulmadı."
  fi
  if [ -d "$APP_DIR" ]; then
    rm -rf "$APP_DIR"
    say "Kaldırıldı: $APP_DIR"
    # Removing the shared env is safe: the npm launcher recreates it on demand.
    rm -rf "$VENV_DIR" "$STAMP" "$DATA_DIR/install.lock"
  else
    note "not: $APP_DIR yok (npm kurulumu olabilir), ortam korundu."
  fi
  say "Hesap ve oturumlar ayrı durur: ~/.local/state/pull1sec"
}

command -v mktemp >/dev/null 2>&1 || err "mktemp gerekli."

case "${1:-}" in
  --uninstall) uninstall_app ;;
  --help | -h) usage ;;
  "") install_app ;;
  *) err "bilinmeyen seçenek: $1 (--help)" ;;
esac
